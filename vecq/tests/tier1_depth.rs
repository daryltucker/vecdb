fn flatten<'a>(es: &'a [DocumentElement], out: &mut Vec<&'a DocumentElement>) {
    for e in es {
        out.push(e);
        flatten(&e.children, out);
    }
}

struct Parsed<'a> {
    source: &'a str,
    all: Vec<&'a DocumentElement>,
    module: Option<&'a Scope>,
}

impl<'a> Parsed<'a> {
    fn named(&self, name: &str, kinds: &[ElementType]) -> Option<&'a DocumentElement> {
        self.all
            .iter()
            .copied()
            .find(|e| e.name.as_deref() == Some(name) && kinds.contains(&e.element_type))
    }

    fn with_content(&self, text: &str) -> Option<&'a DocumentElement> {
        self.all.iter().copied().find(|e| e.content.trim() == text)
    }

    fn scope(&self, name: Option<&str>) -> Option<&'a Scope> {
        match name {
            None => self.module,
            Some(n) => self
                .all
                .iter()
                .find(|e| e.name.as_deref() == Some(n) && e.scope.is_some())
                .and_then(|e| e.scope.as_ref()),
        }
    }

    /// The cell, plus the element it resolved to (for the span check).
    fn cell(&self, probe: &Probe) -> (&'static str, Option<&'a DocumentElement>) {
        match probe {
            Absent => ("—", None),
            Named(n, kinds) => match self.named(n, kinds) {
                Some(e) => ("element", Some(e)),
                None => ("opaque", None),
            },
            Text(t) => match self.with_content(t) {
                Some(e) => ("element", Some(e)),
                None => ("opaque", None),
            },
            Call(callee, scope) => {
                if self
                    .scope(*scope)
                    .is_some_and(|s| s.calls.iter().any(|c| c.callee == *callee))
                {
                    ("span-only", None)
                } else if let Some(e) = self.named(
                    callee,
                    &[ElementType::FunctionCall, ElementType::MethodCall],
                ) {
                    ("element", Some(e))
                } else {
                    ("opaque", None)
                }
            }
            Str(lit, scope) => {
                if self
                    .scope(*scope)
                    .is_some_and(|s| s.strings.iter().any(|x| x.value == *lit))
                {
                    ("span-only", None)
                } else if let Some(e) = self.with_content(&format!("\"{lit}\"")) {
                    ("element", Some(e))
                } else {
                    ("opaque", None)
                }
            }
            Value(var, init) => {
                let Some(v) = self.named(var, VAR) else {
                    return ("opaque", None);
                };
                if let Some(e) = self
                    .all
                    .iter()
                    .copied()
                    .find(|e| e.content.trim() == *init && e.element_type != v.element_type)
                {
                    ("element", Some(e))
                } else if v.attributes.get("value").and_then(|x| x.as_str()) == Some(init) {
                    ("attribute", None)
                } else {
                    ("opaque", None)
                }
            }
        }
    }
}

struct Table {
    label: &'static str,
    rows: Vec<Vec<&'static str>>,
}

async fn table_for(lang: &Lang, span_failures: &mut Vec<String>) -> Table {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/depth")
        .join(lang.file);
    let source = std::fs::read_to_string(&path).unwrap();
    let doc = vecq::parse_file(&source, lang.file_type)
        .await
        .unwrap_or_else(|e| panic!("{}: does not parse: {e}", lang.file));
    let mut all = Vec::new();
    flatten(&doc.elements, &mut all);
    let parsed = Parsed {
        source: &source,
        all,
        module: doc.module.as_ref(),
    };
    let mut rows = Vec::new();
    for (li, level) in LEVELS.iter().enumerate() {
        let mut row = Vec::new();
        for (ki, kind) in KINDS.iter().enumerate() {
            let (cell, resolved) = parsed.cell(&lang.probes[li][ki]);
            if let Some(e) = resolved {
                // The positive half: an `element` cell is reachable AND exact.
                match e.source_span() {
                    Some((s, t)) if parsed.source.get(s..t) == Some(e.content.as_str()) => {}
                    Some((s, t)) => span_failures.push(format!(
                        "{} {level}/{kind}: element {:?} span {s}..{t} is not its content",
                        lang.label, e.name
                    )),
                    None => span_failures.push(format!(
                        "{} {level}/{kind}: element {:?} has no source span",
                        lang.label, e.name
                    )),
                }
            }
            row.push(cell);
        }
        rows.push(row);
    }
    Table {
        label: lang.label,
        rows,
    }
}

fn render_rows(rows: &[Vec<&str>]) -> String {
    let mut s = String::new();
    s.push_str("| level | ");
    s.push_str(&KINDS.join(" | "));
    s.push_str(" |\n|---|");
    s.push_str(&"---|".repeat(KINDS.len()));
    s.push('\n');
    for (level, row) in LEVELS.iter().zip(rows) {
        s.push_str(&format!("| {level} | {} |\n", row.join(" | ")));
    }
    s
}

/// Languages with identical tables share one heading; first-seen order.
fn render(tables: &[Table]) -> String {
    let mut groups: Vec<(String, Vec<&str>)> = Vec::new();
    for t in tables {
        let body = render_rows(&t.rows);
        match groups.iter_mut().find(|(b, _)| *b == body) {
            Some((_, labels)) => labels.push(t.label),
            None => groups.push((body, vec![t.label])),
        }
    }
    let mut out = String::new();
    for (body, labels) in groups {
        out.push_str(&format!("**{}**\n\n{body}\n", labels.join(", ")));
    }
    out.trim_end().to_string()
}

fn manual_block() -> String {
    let manual = std::fs::read_to_string(
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/docs/man_agent.md"),
    )
    .unwrap();
    let start = manual
        .find(BEGIN)
        .expect("manual has the depth-table begin marker");
    let after = start + manual[start..].find("-->").expect("marker closes") + 3;
    let end = manual[after..]
        .find(END)
        .expect("manual has the depth-table end marker")
        + after;
    manual[after..end].trim().to_string()
}

/// The manual's depth table is exactly what the binary does, per language.
/// A mismatch in either direction fails: depth the manual does not claim, or a
/// claim the binary does not meet. The expected block is printed to paste.
#[tokio::test]
async fn the_manual_depth_table_is_what_the_binary_does() {
    let mut span_failures = Vec::new();
    let mut tables = Vec::new();
    for lang in languages() {
        tables.push(table_for(&lang, &mut span_failures).await);
    }
    assert!(
        span_failures.is_empty(),
        "element cells that are not exact:\n  {}",
        span_failures.join("\n  ")
    );
    let expected = render(&tables);
    let actual = manual_block();
    assert!(
        expected == actual,
        "the depth table in vecq/src/docs/man_agent.md (and its copy \
         docs/vecq/AGENT_MANUAL.md) is not what the binary does. If a parser \
         gained or lost depth, say so in the manual in the same commit. Paste \
         this between the depth-table markers:\n\n{expected}\n"
    );
}

/// The release claim, stated as a test so it cannot drift silently: function
/// bodies are opaque in every code language. When this fails, the depth
/// campaign has landed and the manual's sentence changes with it.
#[tokio::test]
async fn function_bodies_are_opaque_in_every_language() {
    let mut ignored = Vec::new();
    for lang in languages() {
        let t = table_for(&lang, &mut ignored).await;
        let body = &t.rows[2];
        assert_eq!(
            (body[0], body[2]),
            ("opaque", "opaque"),
            "{}: a local or a statement inside a function body is now an element — \
             update the manual's depth section",
            lang.label
        );
    }
}
