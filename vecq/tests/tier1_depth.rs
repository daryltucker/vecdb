//! The depth contract: what an agent can reach by selector, per language —
//! stated in the manual, held to the binary here.
//!
//! Coverage gates prove every byte is in an element; they say nothing about
//! which elements exist. A function body can be covered (by the function) and
//! unreachable (no child elements), and an agent reading the manual could not
//! tell the difference. This test computes, per language, a table of levels ×
//! kinds from a fixture that places one distinctly named construct at each
//! level (`tests/fixtures/depth/`), and requires the manual's table to be
//! exactly that. Two consequences:
//!
//! - every cell the manual calls `element` is resolved here, with its exact
//!   span equal to its `content` (the positive half);
//! - every cell it calls `opaque` is checked to have NO element — so the day a
//!   parser gains depth, this fails until the manual says so in the same
//!   commit (the honesty half).
//!
//! Cells: `element` (own element, own span, reachable by selector) ·
//! `attribute` (data on the enclosing element, no span) · `span-only` (a span
//! in `calls[]`/`strings[]`, not an element) · `opaque` (inside its parent's
//! `content`) · `—` (the language has no such construct at that level).

use std::path::PathBuf;
use vecq::types::refs::Scope;
use vecq::types::{DocumentElement, ElementType, FileType};

const LEVELS: [&str; 4] = ["file", "container body", "function body", "block"];
const KINDS: [&str; 6] = [
    "variable",
    "function",
    "statement",
    "call",
    "string",
    "value",
];

const BEGIN: &str = "<!-- depth-table: generated by vecq/tests/tier1_depth.rs";
const END: &str = "<!-- /depth-table -->";

const VAR: &[ElementType] = &[ElementType::Variable, ElementType::Constant];
const FUNC: &[ElementType] = &[
    ElementType::Function,
    ElementType::Kernel,
    ElementType::DeviceFunction,
];

/// How one cell is asked for. Each probe names a construct the fixture places
/// at exactly one level, so "found anywhere" means "found at that level".
enum Probe {
    /// The language has no such construct at this level.
    Absent,
    /// An element with this name and one of these types.
    Named(&'static str, &'static [ElementType]),
    /// An element whose content is exactly this statement.
    Text(&'static str),
    /// A call to this callee; `None` = module scope, `Some(f)` = scope element `f`.
    Call(&'static str, Option<&'static str>),
    /// A string literal with this value, same scope rule.
    Str(&'static str, Option<&'static str>),
    /// The initializer of the named binding: an element with that content, or
    /// `attributes.value` on the binding, or nothing.
    Value(&'static str, &'static str),
}

use Probe::*;

